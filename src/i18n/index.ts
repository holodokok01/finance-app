let currentLang: LangCode = "ru";

export function setLanguage(l: LangCode) {
  currentLang = l;
}

export function getLanguage(): LangCode {
  return currentLang;
}

export function detectLang(): LangCode {
  let c = "";
  try {
    c = String((window as any).Telegram?.WebApp?.initDataUnsafe?.user?.language_code || "");
  } catch (e) {}
  if (!c && typeof navigator !== "undefined") {
    c = navigator.language || "";
  }
  c = c.toLowerCase().slice(0, 2);
  return c === "uk" ? "uk" : c === "ru" ? "ru" : "en";
}

export function L(s: string, v?: Record<string, string | number>, lang: LangCode = currentLang): string {
  if (lang === "ru") {
    let r = s;
    if (v) {
      r = r.replace(/\{(\w+)\}/g, (_, k) => (v[k] != null ? String(v[k]) : ""));
    }
    return r;
  }
  const d = I18N[lang as "uk" | "en"];
  let r = d && d[s] != null ? d[s] : s;
  if (v) {
    r = r.replace(/\{(\w+)\}/g, (_, k) => (v[k] != null ? String(v[k]) : ""));
  }
  return r;
}

export function plural(n: number, a: string, b: string, c: string, lang: LangCode = currentLang): string {
  const w = PLW[a];
  if (w && lang === "en") {
    return n === 1 ? w.en[0] : w.en[1];
  }
  if (w && lang === "uk") {
    const m2 = n % 10;
    const h2 = n % 100;
    return w.uk[m2 === 1 && h2 !== 11 ? 0 : m2 >= 2 && m2 <= 4 && (h2 < 10 || h2 >= 20) ? 1 : 2];
  }
  const m = n % 10;
  const h = n % 100;
  return m === 1 && h !== 11 ? a : m >= 2 && m <= 4 && (h < 10 || h >= 20) ? b : c;
}
